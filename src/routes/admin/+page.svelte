<script lang="ts">
	import { untrack } from 'svelte';
	import { enhance } from '$app/forms';
	import { fold } from '#lib/text.ts';
	import type { PageProps } from './$types';

	let { data, form }: PageProps = $props();

	const bride = $derived(data.role === 'bride');
	const greekTime = new Intl.DateTimeFormat('en-GB', { timeZone: 'Europe/Athens', day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });

	// Filtered in the browser: the list is small and this keeps typing smooth.
	let query = $state(untrack(() => data.q));
	const songs = $derived.by(() => {
		const q = fold(query);
		if (!q) return data.songs;
		return data.songs.filter((s) => fold(`${s.title} ${s.artist} ${s.guestName} ${s.guestLabel}`).includes(q));
	});

	const confirmSubmit = (message: string) => (event: MouseEvent) => {
		if (!confirm(message)) event.preventDefault();
	};

	async function downloadQr() {
		if (!data.qrSvg) return;
		const img = new Image();
		img.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(data.qrSvg)}`;
		await img.decode();
		const canvas = document.createElement('canvas');
		canvas.width = canvas.height = 1024;
		const ctx = canvas.getContext('2d')!;
		ctx.imageSmoothingEnabled = false;
		ctx.drawImage(img, 0, 0, 1024, 1024);
		const a = document.createElement('a');
		a.href = canvas.toDataURL('image/png');
		a.download = 'maria-frank-songs-qr.png';
		a.click();
	}
</script>

<section class="top">
	<div>
		<p class="progress"><strong>{data.progress.done}</strong> of <strong>{data.progress.total}</strong> guests have picked</p>
		{#if data.progress.notYet.length}
			<details>
				<summary>Who hasn't picked yet ({data.progress.notYet.length})</summary>
				<ul class="not-yet">
					{#each data.progress.notYet as g (g.id)}
						<li>{g.name}{g.label ? ` (${g.label})` : ''}{g.picks ? ` · ${g.picks} of 2` : ''}</li>
					{/each}
				</ul>
			</details>
		{/if}
	</div>
	<a class="btn download" href="/admin/export.csv" download>Download list (CSV)</a>
</section>

{#if form?.message}
	<p class="notice" role="status">{form.message}</p>
{/if}

<label class="label" for="q">Search by song, artist or guest</label>
<input id="q" class="field search" type="search" bind:value={query} placeholder="e.g. Eleni, ABBA, Zorba" autocomplete="off" />

<p class="count">{songs.length} {songs.length === 1 ? 'song' : 'songs'}{query.trim() ? ` matching "${query.trim()}"` : ''}</p>

<ul class="songs">
	{#each songs as s (s.id)}
		<li class="song">
			{#if s.artworkUrl}<img src={s.artworkUrl} alt="" loading="lazy" />{:else}<span class="art"></span>{/if}
			<div class="what">
				<strong>{s.title}</strong>
				<span>{s.artist}</span>
				{#if s.source === 'typed'}<em class="badge">typed by guest</em>{/if}
			</div>
			<div class="who">
				<span>{s.guestName}{s.guestLabel ? ` (${s.guestLabel})` : ''}</span>
				<small>{greekTime.format(new Date(s.createdAt))}</small>
			</div>
			{#if bride}
				<div class="actions">
					<form method="POST" action="?/removeSong" use:enhance>
						<input type="hidden" name="songId" value={s.id} />
						<button class="small-btn" onclick={confirmSubmit(`Remove "${s.title}"? ${s.guestName} will be able to pick a replacement.`)}>Remove</button>
					</form>
					<form method="POST" action="?/resetGuest" use:enhance>
						<input type="hidden" name="guestId" value={s.guestId} />
						<button class="small-btn" onclick={confirmSubmit(`Reset ${s.guestName}? Both of their songs will be removed and they can pick 2 again.`)}>Reset guest</button>
					</form>
				</div>
			{/if}
		</li>
	{:else}
		<li class="empty">No songs yet.</li>
	{/each}
</ul>

{#if bride}
	<section class="settings">
		<form method="POST" action="?/closeDate" use:enhance={() => async ({ update }) => update({ reset: false })} class="close-date">
			<label class="label" for="closeDate">Song picks close at the end of (Greek time)</label>
			<div class="row">
				<input class="field" id="closeDate" name="closeDate" type="date" value={data.closeDate} required />
				<button class="btn">Save</button>
			</div>
		</form>

		<div class="qr">
			<p class="label">Guest link</p>
			<p class="link">{data.guestLink}</p>
			<!-- eslint-disable-next-line svelte/no-at-html-tags -- generated by the qrcode library on the server -->
			<div class="qr-img">{@html data.qrSvg}</div>
			<button class="btn" onclick={downloadQr}>Download QR code</button>
		</div>
	</section>
{/if}

